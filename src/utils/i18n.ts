export function translateText(
  lang: AppLanguage,
  key: string,
  params?: Record<string, string | number>
): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.pt;
  let value = dict[key] || TRANSLATIONS.pt[key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      value = value.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return value;
}

export function translateDynamicText(lang: AppLanguage, text?: string): string {
  if (!text || lang === 'pt') return text || '';

  const trimmed = text.trim();
  if (!trimmed) return text;

  if (DYNAMIC_PHRASES[trimmed]) {
    const exact = DYNAMIC_PHRASES[trimmed][lang];
    return text.replace(trimmed, exact);
  }

  let out = text;

  // Apply exact dictionary entries when they appear as substrings
  for (const [ptPhrase, translations] of Object.entries(DYNAMIC_PHRASES)) {
    if (ptPhrase.length > 8 && out.includes(ptPhrase)) {
      out = out.split(ptPhrase).join(translations[lang]);
    }
  }

  const replacements = lang === 'es' ? ES_REPLACEMENTS : EN_REPLACEMENTS;
  for (const [regex, replacement] of replacements) {
    out = out.replace(regex, replacement);
  }

  return out;
}
